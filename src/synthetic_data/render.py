def render_html(report: Dict[str, Any]) -> str:
    picks = []
    for pick in report.get("top_picks", []):
        entry = dict(pick)
        entry["published"] = format_day(pick["published"])
        picks.append(entry)

    return HTML_TEMPLATE.render(
        subject=subject_line(report),
        preview=report["trend"].strip().split(". ")[0] + ".",
        week=format_week(report["week_start"], report["week_end"]),
        trend=report["trend"].strip(),
        top_picks=picks,
        tools=report.get("tools", []),
        worth_a_look=report.get("worth_a_look", []),
    )


def render_all_links(report: Dict[str, Any]) -> List[Dict[str, str]]:
    """Every (label, url) that will appear in the email."""
    links = []
    for pick in report.get("top_picks", []):
        links.append({"label": pick["title"], "url": pick["url"]})
    for tool in report.get("tools", []):
        links.append({"label": tool["name"], "url": tool["url"]})
    for item in report.get("worth_a_look", []):
        links.append({"label": item["title"], "url": item["url"]})
    return links
