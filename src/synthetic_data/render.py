"""Render the weekly report to Markdown and to the HTML email body.

The report data is plain Python/YAML so the rest of the pipeline only has to
produce a dict; formatting lives here. Section order follows the spec
(section 5): subject, trend, top picks, new tools, worth a look, footer.
"""

from datetime import date, datetime
from typing import Any, Dict, List

from jinja2 import Template

MONTHS = (
    "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
)


def format_day(value) -> str:
    """'2026-10-29' -> '29 Oct 2026'."""
    if isinstance(value, datetime):
        value = value.date()
    if isinstance(value, str):
        value = date.fromisoformat(value[:10])
    return f"{value.day} {MONTHS[value.month - 1]} {value.year}"


def format_week(week_start, week_end) -> str:
    """'26 Oct – 1 Nov 2026' with the month repeated only when it changes."""
    if isinstance(week_start, str):
        week_start = date.fromisoformat(week_start)
    if isinstance(week_end, str):
        week_end = date.fromisoformat(week_end)
    left = f"{week_start.day} {MONTHS[week_start.month - 1]}"
    right = f"{week_end.day} {MONTHS[week_end.month - 1]}"
    if week_start.month == week_end.month:
        right = str(week_end.day)
    return f"{left} – {right} {week_end.year}"


def subject_line(report: Dict[str, Any]) -> str:
    return f"Synthetic Data Weekly — Week of {format_week(report['week_start'], report['week_end'])}"


def render_markdown(report: Dict[str, Any]) -> str:
    lines: List[str] = []
    lines.append(f"**Subject:** {subject_line(report)}")
    lines.append("")
    lines.append("*Well7 Research Lab · Privacy-first tabular and time-series synthetic data research.*")
    lines.append("")
    lines.append("## Trend of the week")
    lines.append("")
    lines.append(report["trend"].strip())
    lines.append("")
    lines.append("## Top picks")
    lines.append("")

    for index, pick in enumerate(report.get("top_picks", []), start=1):
        lines.append(f"{index}. [{pick['title']}]({pick['url']})")
        lines.append(f"   *{pick['source']} · {format_day(pick['published'])}*")
        for chunk in pick["summary"].strip().split("\n\n"):
            lines.append(f"   {' '.join(chunk.split())}")
        lines.append("")

    lines.append("## New tools and datasets")
    lines.append("")
    tools = report.get("tools", [])
    if tools:
        for tool in tools:
            lines.append(f"- [{tool['name']}]({tool['url']}) — {tool['note'].strip()}")
    else:
        lines.append("_Nothing worth listing this week._")
    lines.append("")

    lines.append("## Worth a look (lower priority)")
    lines.append("")
    extra = report.get("worth_a_look", [])
    if extra:
        for item in extra:
            lines.append(f"- [{item['title']}]({item['url']}) — {item['note'].strip()}")
    else:
        lines.append("_Nothing this week._")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Auto-generated by the Synthetic Data Research Agent. Reply with feedback.")
    lines.append("")
    return "\n".join(lines)


