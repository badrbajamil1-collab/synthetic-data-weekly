"""Verify the rendered report against the spec's format and quality rules.

Checks the artefacts on disk, not the in-memory objects, so this catches
rendering mistakes (unfilled templates, dropped links, wrong section order).
"""

import json
import re
import sys
from datetime import date, timedelta
from html.parser import HTMLParser
from pathlib import Path

import yaml

# Each run lives in progress/week-YYYY-MM-DD/ (source.yaml + artefacts).
# Default: the newest one. Pass a source.yaml path to check a specific week.
REPORT = sys.argv[1] if len(sys.argv) > 1 else None
if REPORT is None:
    found = sorted(Path("progress").glob("week-*/source.yaml"))
    if not found:
        raise SystemExit("no report found under progress/week-*/source.yaml")
    REPORT = str(found[-1])

data = yaml.safe_load(open(REPORT, encoding="utf-8"))
# dump_report omits empty sections on purpose: 0 tools / 0 worth-a-look are
# valid per the brief. The verifier still needs the keys to exist.
for _section in ("top_picks", "tools", "worth_a_look"):
    data.setdefault(_section, [])
BASE = Path(REPORT).parent
md = (BASE / "report.md").read_text(encoding="utf-8")
html = (BASE / "report.html").read_text(encoding="utf-8")
try:
    log = json.loads((BASE / "run_log.json").read_text(encoding="utf-8"))
    if not isinstance(log, dict):
        raise ValueError("run_log.json is not an object")
except (OSError, ValueError) as exc:
    # Keep going: the report-level checks still have something to say, and a
    # traceback here used to hide every check behind a crashed import.
    log = {}
    print(f"  WARN  run_log.json unreadable — {type(exc).__name__}: {exc}")
NEW = log.get("schema") == "2026-11-11"

failures = []


def check(name, condition, detail=""):
    print(f"  {'PASS' if condition else 'FAIL'}  {name}{(' — ' + detail) if detail and not condition else ''}")
    if not condition:
        failures.append(name)


class AnchorParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            for key, value in attrs:
                if key == "href":
                    self.hrefs.append(value)


parser = AnchorParser()
parser.feed(html)

expected = [p["url"] for p in data["top_picks"]] + [t["url"] for t in data["tools"]] + [
    i["url"] for i in data["worth_a_look"]
]

print("HTML")
check("no unrendered jinja", "{{" not in html and "{%" not in html)
check("every expected link present", all(url in parser.hrefs for url in expected),
      f"missing {[u for u in expected if u not in parser.hrefs]}")
check("no extra links", len(parser.hrefs) == len(expected), f"{len(parser.hrefs)} vs {len(expected)}")
check("anchor count matches", len(parser.hrefs) == len(set(parser.hrefs)))
check("subject present", "Synthetic Data Weekly" in html)
check("footer present", "Reply with feedback." in html)

print("Markdown")
check("subject line first", md.startswith("**Subject:** Synthetic Data Weekly — Week of "))
section_order = ["Trend of the week", "Top picks", "New tools and datasets", "Worth a look (lower priority)"]
if NEW and log.get("trend_omitted"):
    section_order = [s for s in section_order if s != "Trend of the week"]
    check("trend heading is absent when the trend was omitted", "Trend of the week" not in md)
positions = [md.find(s) for s in section_order]
check("sections in spec order", all(p >= 0 for p in positions) and positions == sorted(positions))
check("footer last", md.rstrip().endswith("Auto-generated by the Synthetic Data Research Agent. Reply with feedback."))
min_picks = 1 if NEW else 5
check(f"top picks within {min_picks}-10", min_picks <= len(data["top_picks"]) <= 10, str(len(data["top_picks"])))
check("tools within 0-5", 0 <= len(data["tools"]) <= 5, str(len(data["tools"])))
check("worth a look within 0-5", 0 <= len(data["worth_a_look"]) <= 5, str(len(data["worth_a_look"])))
check("no duplicate links", len(expected) == len(set(expected)))
check("every link in markdown", all(url in md for url in expected))
if NEW and isinstance(log.get("score_floors"), dict):
    floors = log["score_floors"]
    below_floor = []
    for sec_key, floor_key in (("top_picks", "top"), ("tools", "tools"), ("worth_a_look", "worth")):
        floor_val = floors.get(floor_key, 0)
        for entry in data.get(sec_key, []):
            score = entry.get("score")
            # A missing or non-numeric score is not "above the floor":
            # compose_sections' _clears() rejects it, and so must the
            # verifier. The isinstance guard also stops a string score from
            # raising TypeError out of the import.
            if (
                isinstance(score, bool)
                or not isinstance(score, (int, float))
                or score < floor_val
            ):
                below_floor.append(
                    f"{sec_key}:{entry.get('title') or entry.get('name')}:{score}<{floor_val}"
                )
    check("section score floors met", not below_floor, str(below_floor))
if NEW:
    # Check the RENDERED artefacts, not just source.yaml: that is what the
    # reader sees. The old gate (`if log.get("why_it_matters")`) skipped the
    # whole block exactly when the field was missing, so it could never fail.
    top_picks = data.get("top_picks") or []
    present = [
        p for p in top_picks if str(p.get("why_it_matters") or "").strip()
    ]
    # The producer flag is a capability flag: it is set when at least one
    # line was written, not when every pick has one. Requiring a line per
    # pick failed weeks the pipeline considers valid (and every offline
    # --no-llm report). What must hold is that the flag is truthful.
    if bool(log.get("why_it_matters")) != bool(present):
        check(
            "run log's why_it_matters flag matches the artefact",
            False,
            f"flag={bool(log.get('why_it_matters'))} present={len(present)}/{len(top_picks)}",
        )
    else:
        check("run log's why_it_matters flag matches the artefact", True)
    if present:
        check("why it matters line is rendered in markdown", "Why it matters for Well7" in md)
        check("why it matters line is rendered in html", "Why it matters for Well7" in html)
if NEW and isinstance(log.get("source_counts"), dict) and log["source_counts"]:
    sc = log["source_counts"]
    expected_counts_line = (
        "Sources this week: "
        + " · ".join(f"{key} {value}" for key, value in sc.items())
        + "."
    )
    # The exact footer line, positioned before the contractual closing
    # sentence. `any(key in md and value in md)` passed on accidental matches
    # elsewhere in the body.
    check(
        "per-source counts footer line is rendered",
        expected_counts_line in md,
        expected_counts_line,
    )
    check(
        "source counts appear before the contractual footer",
        md.find(expected_counts_line) != -1
        and md.find(expected_counts_line)
        < md.rstrip().rfind(
            "Auto-generated by the Synthetic Data Research Agent. Reply with feedback."
        ),
    )

print("Dates")
try:
    week_end = date.fromisoformat(str(data.get("week_end") or ""))
except ValueError:
    week_end = None
check("week_end is a usable date", week_end is not None, str(data.get("week_end")))
if week_end is not None:
    cutoff = week_end - timedelta(days=6)
    bad = []
    for pick in data["top_picks"]:
        try:
            day = date.fromisoformat(str(pick["published"]))
        except (KeyError, ValueError):
            bad.append(str(pick.get("title") or "")[:50])
            continue
        if not (cutoff <= day <= week_end):
            bad.append(str(pick.get("title") or "")[:50])
    check("top picks inside the reported week", not bad, str(bad))
    bad_rest = []
    for entry in [*data["tools"], *data["worth_a_look"]]:
        if not entry.get("published"):
            continue
        try:
            day = date.fromisoformat(str(entry["published"]))
        except ValueError:
            bad_rest.append(str(entry.get("published")))
            continue
        if not (cutoff <= day <= week_end):
            bad_rest.append(str(entry.get("published")))
    check("tools and worth a look inside the reported week", not bad_rest, str(bad_rest))
    if NEW and log.get("week_mode") == "run_date":
        try:
            week_start = date.fromisoformat(
                str(data.get("week_start") or log.get("week_start") or "")
            )
        except ValueError:
            check(
                "Sunday-Saturday 7-day window",
                False,
                "missing or unparseable week_start",
            )
        else:
            check(
                "Sunday-Saturday 7-day window",
                week_start.weekday() == 6
                and week_end.weekday() == 5
                and (week_end - week_start).days == 6,
                f"{week_start}..{week_end}",
            )

print("Counts")
check(
    "run log records counts",
    int(log.get("items_found") or 0) > 0 and "links_dead" in log,
    str(log),
)
check("no dead links recorded", int(log.get("links_dead") or 0) == 0, str(log.get("links_dead")))
check(
    "found is the raw count, not the deduped one",
    int(log.get("items_found") or 0) >= int(log.get("items_after_dedupe") or 0) > 0,
    f"found={log.get('items_found')} after_dedupe={log.get('items_after_dedupe')}",
)
check(
    "source errors were actually checked",
    isinstance(log.get("source_errors"), list) and log.get("source_errors") == [],
    str(log.get("source_errors")),
)

print("PDF")
# A missing week_end used to raise KeyError here, after every other check had
# already run. Fail the PDF check instead of the whole verifier.
pdf_label = data.get("week_end") or log.get("week_end") or "unknown"
pdf = BASE / f"Synthetic_Data_Weekly_{pdf_label}.pdf"
check("pdf exists", pdf.exists(), str(pdf))
check("pdf non-trivial size", pdf.exists() and pdf.stat().st_size > 40_000, f"{pdf.stat().st_size if pdf.exists() else 0} bytes")

print()
if failures:
    print(f"{len(failures)} FAILURE(S): {failures}")
    raise SystemExit(1)
print("All report checks passed.")
