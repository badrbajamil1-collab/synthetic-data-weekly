"""Verify the rendered report against the spec's format and quality rules.

Checks the artefacts on disk, not the in-memory objects, so this catches
rendering mistakes (unfilled templates, dropped links, wrong section order).
"""

import json
import re
import sys
from datetime import date, timedelta
from html.parser import HTMLParser
from pathlib import Path

import yaml

# Each run lives in progress/week-YYYY-MM-DD/ (source.yaml + artefacts).
# Default: the newest one. Pass a source.yaml path to check a specific week.
REPORT = sys.argv[1] if len(sys.argv) > 1 else None
if REPORT is None:
    found = sorted(Path("progress").glob("week-*/source.yaml"))
    if not found:
        raise SystemExit("no report found under progress/week-*/source.yaml")
    REPORT = str(found[-1])

data = yaml.safe_load(open(REPORT, encoding="utf-8"))
BASE = Path(REPORT).parent
md = (BASE / "report.md").read_text(encoding="utf-8")
html = (BASE / "report.html").read_text(encoding="utf-8")

failures = []


def check(name, condition, detail=""):
    print(f"  {'PASS' if condition else 'FAIL'}  {name}{(' — ' + detail) if detail and not condition else ''}")
    if not condition:
        failures.append(name)


class AnchorParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            for key, value in attrs:
                if key == "href":
                    self.hrefs.append(value)


parser = AnchorParser()
parser.feed(html)

expected = [p["url"] for p in data["top_picks"]] + [t["url"] for t in data["tools"]] + [
    i["url"] for i in data["worth_a_look"]
]

print("HTML")
check("no unrendered jinja", "{{" not in html and "{%" not in html)
check("every expected link present", all(url in parser.hrefs for url in expected),
      f"missing {[u for u in expected if u not in parser.hrefs]}")
check("no extra links", len(parser.hrefs) == len(expected), f"{len(parser.hrefs)} vs {len(expected)}")
check("anchor count matches", len(parser.hrefs) == len(set(parser.hrefs)))
check("subject present", "Synthetic Data Weekly" in html)
check("footer present", "Reply with feedback." in html)

print("Markdown")
check("subject line first", md.startswith("**Subject:** Synthetic Data Weekly — Week of "))
section_order = ["Trend of the week", "Top picks", "New tools and datasets", "Worth a look (lower priority)"]
positions = [md.find(s) for s in section_order]
check("sections in spec order", all(p >= 0 for p in positions) and positions == sorted(positions))
check("footer last", md.rstrip().endswith("Auto-generated by the Synthetic Data Research Agent. Reply with feedback."))
check("top picks within 5-10", 5 <= len(data["top_picks"]) <= 10, str(len(data["top_picks"])))
check("tools within 0-5", 0 <= len(data["tools"]) <= 5, str(len(data["tools"])))
check("worth a look within 0-5", 0 <= len(data["worth_a_look"]) <= 5, str(len(data["worth_a_look"])))
check("no duplicate links", len(expected) == len(set(expected)))
check("every link in markdown", all(url in md for url in expected))

print("Dates")
week_end = date.fromisoformat(str(data["week_end"]))
cutoff = week_end - timedelta(days=6)
bad = [p["title"][:50] for p in data["top_picks"] if not (cutoff <= date.fromisoformat(str(p["published"])) <= week_end)]
check("top picks inside the reported week", not bad, str(bad))

print("Counts")
log = json.loads((BASE / "run_log.json").read_text(encoding="utf-8"))
check("run log records counts", log["items_found"] > 0 and "links_dead" in log, str(log))
check("no dead links recorded", log["links_dead"] == 0, str(log["links_dead"]))
check(
    "found is the raw count, not the deduped one",
    log["items_found"] >= log["items_after_dedupe"] > 0,
    f"found={log['items_found']} after_dedupe={log['items_after_dedupe']}",
)
check(
    "source errors were actually checked",
    isinstance(log.get("source_errors"), list) and log.get("source_errors") == [],
    str(log.get("source_errors")),
)

print("PDF")
pdf = BASE / f"Synthetic_Data_Weekly_{data['week_end']}.pdf"
check("pdf exists", pdf.exists(), str(pdf))
check("pdf non-trivial size", pdf.exists() and pdf.stat().st_size > 40_000, f"{pdf.stat().st_size if pdf.exists() else 0} bytes")

print()
if failures:
    print(f"{len(failures)} FAILURE(S): {failures}")
    raise SystemExit(1)
print("All report checks passed.")
