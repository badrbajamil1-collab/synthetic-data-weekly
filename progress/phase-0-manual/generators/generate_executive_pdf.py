class NumberedCanvas(canvas.Canvas):
    """Running header (page 2+) and footer with live page numbering."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont(FONT_BOLD, 7.5)
        self.setFillColor(COLOR_MUTED)

        if self._pageNumber > 1:
            self.drawString(36, PAGE_H - 24, "WELL7 RESEARCH LAB — SYNTHETIC DATA INTELLIGENCE")
            self.setFont(FONT_REG, 7.5)
            self.drawRightString(PAGE_W - 36, PAGE_H - 24, WEEK_UPPER)
            self.setStrokeColor(COLOR_BORDER)
            self.setLineWidth(0.5)
            self.line(36, PAGE_H - 28, PAGE_W - 36, PAGE_H - 28)

        self.setFont(FONT_REG, 7.5)
        self.setFillColor(COLOR_MUTED)
        self.drawString(36, 20, "Auto-generated by the Synthetic Data Research Agent · Reply with feedback")
        self.setFont(FONT_BOLD, 7.5)
        self.drawRightString(PAGE_W - 36, 20, f"Page {self._pageNumber} of {page_count}")
        self.setStrokeColor(COLOR_BORDER)
        self.setLineWidth(0.5)
        self.line(36, 29, PAGE_W - 36, 29)

        self.restoreState()


